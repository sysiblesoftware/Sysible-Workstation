"""A second publish to the same suite must succeed.

Both OS repos failed EVERY release publish once the aptly database had
recorded one publication. The job log ended:

    Snapshot sysible-stable-20261125171418 successfully created.
    ERROR: prefix/distribution already used by another published repo:
      filesystem:local:./sysible-stable [amd64, arm64] publishes
      {main: [sysible-stable-20261125154737]: ...}

The cause was the line before it, which the log could not show:

    aptly publish drop "$SUITE" "$PREFIX" >/dev/null 2>&1 || true

CI's publish directory is ephemeral while the aptly DATABASE is restored from
R2, so aptly always believes a publication exists for a directory that is
empty. The script dropped it and recreated it — and when the drop failed, for
any reason at all, `|| true` swallowed the reason and the create died two
lines later complaining about the publication the drop was supposed to remove.
Every release since silently reached GitHub but never reached apt.

Note what this test does NOT claim: the drop's own failure was never
reproduced outside CI. Restoring the old drop-and-create passes locally, which
is the point — the fix is not "the drop was wrong", it is that the outcome no
longer depends on a drop at all, and nothing is swallowed if it does fail.

aptly's primitives for "replace what is published here" are `publish switch`
(snapshot) and `publish update` (repo). Both rewrite the whole tree, verified
against an empty publish dir: pool/ and dists/ come back complete with
InRelease, Release and Release.gpg.
"""
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/publish-repo.sh"
TEXT = SCRIPT.read_text(encoding="utf-8")


def code():
    """The script with comments stripped.

    Non-negotiable here: this file's own subject matter is quoted at length in
    the comments above the code being asserted on, and several guards in this
    project have passed by matching their subject inside a comment.
    """
    out = []
    for line in TEXT.splitlines():
        stripped = re.sub(r"(^|\s)#.*$", "", line)
        if stripped.strip():
            out.append(stripped)
    return "\n".join(out)


def test_no_aptly_failure_is_swallowed():
    """The whole bug in one line. Any aptly call whose output AND exit status
    are both discarded can fail invisibly."""
    for line in code().splitlines():
        if "aptly" not in line:
            continue
        swallowed = (">/dev/null 2>&1" in line or ">/dev/null 2>&1" in line) and (
            "|| true" in line or line.rstrip().endswith("|| :"))
        assert not swallowed, (
            f"this aptly call discards both its output and its exit status, "
            f"which is how the publish failed silently for months:\n    {line}"
        )


def test_the_publication_is_replaced_not_dropped_and_recreated():
    c = code()
    assert "aptly publish drop" not in c, (
        "publish drop is back. The published tree is regenerated by `publish "
        "switch`/`publish update`; dropping first is what made an existing "
        "publication fatal."
    )
    assert "aptly publish switch" in c, \
        "nothing switches an existing stable publication to the new snapshot"
    assert "aptly publish update" in c, \
        "nothing updates an existing dev publication"


def test_both_suites_handle_first_publish_and_republish():
    """Four paths, and all four are reachable: a suite that has never been
    published needs `snapshot`/`repo`, one that has needs `switch`/`update`."""
    c = code()
    for needed in ("aptly publish snapshot", "aptly publish repo",
                   "aptly publish switch", "aptly publish update"):
        assert needed in c, f"missing the {needed!r} path"


def test_an_unreadable_database_is_fatal():
    """It must not read as 'nothing is published there'. That would take the
    create path and resurrect the original error with the cause hidden again."""
    c = code()
    assert "aptly publish list -raw" in c, \
        "nothing asks the database what is already published"
    m = re.search(r"PUBLISHED=\$\(aptly publish list -raw\)\s*\|\|\s*\{", c)
    assert m, (
        "the publication lookup does not fail hard. If aptly cannot read its "
        "database the script must refuse to publish, not assume an empty one."
    )
    assert "exit 1" in c[m.end():m.end() + 400], \
        "the unreadable-database branch does not exit nonzero"


def test_the_snapshot_name_is_unique_not_merely_timestamped():
    """A UTC second is not unique. Server and Workstation share ONE aptly
    database, so two release jobs finishing together collide with 'snapshot
    with name ... already exists' — reproduced in a local harness, and the same
    one-second collision already bit the version suffix."""
    c = code()
    m = re.search(r'SNAP="[^"]*"', c)
    assert m, "no snapshot name is constructed"
    snap = m.group(0)
    assert "date -u +%Y%m%d%H%M%S" in snap, "the snapshot name is not monotonic"
    assert "GITHUB_RUN_ID" in snap, (
        f"the snapshot name has only a UTC second to make it unique, which is "
        f"not enough for two publishes in the same second: {snap}"
    )


def test_an_empty_endpoint_becomes_aptlys_root_prefix():
    """aptly spells "root of this endpoint" as "."; an empty positional prefix
    is a different thing, and `publish switch` then reports the publication
    missing. It broke the second of two local publishes while the first
    passed, because `publish snapshot` normalizes an empty prefix itself."""
    c = code()
    assert 'PREFIX="."' in c, (
        "an unset SYSIBLE_APTLY_ENDPOINT no longer normalizes to the '.' "
        "prefix, so a repeat local publish will not find its publication"
    )
    assert 'PREFIX="${ENDPOINT}."' in c or 'PREFIX="$ENDPOINT."' in c, (
        "an endpoint with no path is not normalized to '<endpoint>:.', which "
        "is the form `aptly publish list -raw` prints and this script matches"
    )


def test_the_prefix_normalisation_actually_produces_those_forms():
    """Run the case block rather than trust it."""
    block = re.search(r'case "\$ENDPOINT" in.*?esac', TEXT, re.S)
    assert block, "the prefix normalisation case block is gone"
    for endpoint, expected in (("", "."),
                               ("filesystem:local:", "filesystem:local:."),
                               ("s3:sysible:apt", "s3:sysible:apt")):
        r = subprocess.run(
            ["sh", "-c", f'ENDPOINT="{endpoint}"\n{block.group(0)}\nprintf %s "$PREFIX"'],
            capture_output=True, text=True, check=True)
        assert r.stdout == expected, (
            f"endpoint {endpoint!r} normalised to {r.stdout!r}, expected {expected!r}"
        )


@pytest.mark.skipif(shutil.which("aptly") is None, reason="aptly not installed")
def test_the_published_tree_is_complete_after_a_republish(tmp_path):
    """End-to-end, shaped like CI: publish, throw the tree away, publish again,
    and require a complete tree both times.

    Scope, honestly: the drop-and-recreate version PASSES this, because the
    drop succeeds outside CI — reproducing that failure needs CI's restored
    database, which is not available here. What this does cover is that
    switch/update genuinely rebuild a thrown-away tree, which is the property
    the fix rests on. The structural tests above are what pin the rest. It also
    skips where there is no aptly or no usable gpg-agent, so it adds
    confidence, never a guarantee."""
    gnupg = Path("/tmp") / f"sysible-test-gpg-{tmp_path.name}"
    gnupg.mkdir(mode=0o700, exist_ok=True)
    # Inherit PATH: hardcoding it made this skip even where aptly WAS
    # installed, just not in /usr/bin.
    env = {"GNUPGHOME": str(gnupg), "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
           "SYSIBLE_APTLY_ENDPOINT": "filesystem:local:",
           "SYSIBLE_GPG_KEY": "maintainers@sysible.com", "HOME": str(tmp_path)}
    keygen = subprocess.run(
        ["gpg", "--batch", "--pinentry-mode", "loopback", "--passphrase", "",
         "--quick-gen-key", "Sysible Test <maintainers@sysible.com>",
         "rsa2048", "sign", "never"], capture_output=True, text=True, env=env)
    if keygen.returncode != 0:
        pytest.skip(f"could not create a test signing key: {keygen.stderr[-200:]}")

    db, pub = tmp_path / "db", tmp_path / "public"
    repo = tmp_path / "repo"
    (repo / "scripts").mkdir(parents=True)
    (repo / "dist").mkdir()
    shutil.copy(SCRIPT, repo / "scripts/publish-repo.sh")
    (repo / "scripts/publish-repo.sh").chmod(0o755)
    (tmp_path / ".aptly.conf").write_text(
        '{"rootDir": "%s", "architectures": ["amd64","arm64"],'
        ' "gpgProvider": "gpg",'
        ' "FileSystemPublishEndpoints": {"local": {"rootDir": "%s",'
        ' "linkMethod": "copy"}}}' % (db, pub), encoding="utf-8")

    d = tmp_path / "pkg/DEBIAN"
    d.mkdir(parents=True)
    (d / "control").write_text(
        "Package: sysible-test\nVersion: 1.0\nArchitecture: all\n"
        "Maintainer: t <t@t>\nDescription: t\n", encoding="utf-8")
    subprocess.run(["dpkg-deb", "-b", str(tmp_path / "pkg"),
                    str(repo / "dist/sysible-test_1.0_all.deb")],
                   check=True, capture_output=True)

    for attempt in (1, 2):
        shutil.rmtree(pub, ignore_errors=True)   # ephemeral publish dir
        pub.mkdir()
        r = subprocess.run([str(repo / "scripts/publish-repo.sh"), "sysible-stable"],
                           capture_output=True, text=True, env=env, cwd=repo)
        assert r.returncode == 0, (
            f"publish attempt {attempt} failed:\n{r.stdout[-1500:]}\n{r.stderr[-1500:]}")
        for rel in ("dists/sysible-stable/InRelease",
                    "dists/sysible-stable/Release",
                    "dists/sysible-stable/Release.gpg"):
            assert (pub / rel).is_file(), f"attempt {attempt}: missing {rel}"
        assert list(pub.glob("pool/**/sysible-test_1.0_all.deb")), \
            f"attempt {attempt}: the .deb is not in the published pool"
